#!/usr/bin/env python3
"""Values overlay for the opentelemetry-kube-stack chart that puts the Rancher Project NAME on the metrics.

The collector only sees the Project ID (namespace label field.cattle.io/projectId -> rancher.project.id, see
otel-kube-stack-values.yaml). This script turns the Project list of the Rancher local cluster into a `transform`
processor with one rule per Project: where rancher.project.id is p-xxxxx, set rancher.project.name. In
Elasticsearch that is resource.attributes.rancher.project.name, a real field the dashboard's Project filter can
list (build_dashboard.py --project-name-field).

  kubectl get projects.management.cattle.io -A -o json > projects.json      # on the Rancher local cluster
  ./build_collector_values.py projects.json --out otel-kube-stack-project-names.yaml
  helm upgrade ... -f <your values>.yaml -f otel-kube-stack-values.yaml -f otel-kube-stack-project-names.yaml

The processor must also be listed in the metrics pipeline, after k8s_attributes. Helm replaces lists, so the
overlay cannot add one entry: either add `transform/rancher_project_names` to the pipeline in your own values, or
pass the whole list with --pipeline and the overlay sets it.

Run it again and redeploy after adding or renaming Projects. Only metrics collected after the rollout carry the
name. Standard library only; the output is JSON-flavoured YAML.
"""

import argparse
import json
import sys

import build_dashboard as bd

PROCESSOR = "transform/rancher_project_names"
ID_ATTR = "rancher.project.id"
NAME_ATTR = "rancher.project.name"


def ottl_str(v):
    """OTTL string literal. `$` is doubled: the collector expands ${...} in its configuration."""
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$") + '"'


def statements(names):
    return [f'set(attributes["{NAME_ATTR}"], {ottl_str(name)}) where attributes["{ID_ATTR}"] == {ottl_str(pid)}'
            for pid, name in sorted(names.items())]


def values(names, collector="daemon", pipeline=None):
    config = {"processors": {PROCESSOR: {
        "error_mode": "ignore",
        "metric_statements": [{"context": "resource", "statements": statements(names)}]}}}
    if pipeline:
        config["service"] = {"pipelines": {"metrics": {"processors": pipeline}}}
    return {"collectors": {collector: {"config": config}}}


def render(names, collector="daemon", pipeline=None):
    head = [f"# Generated by kibana/build_collector_values.py: {len(names)} Rancher Projects, ID -> name.",
            "# Do not edit; run the script again after adding or renaming Projects, then redeploy the collector."]
    if not pipeline:
        head.append(f"# Add {PROCESSOR} to service.pipelines.metrics.processors of collector \"{collector}\",")
        head.append("# after k8s_attributes (or generate with --pipeline).")
    return "\n".join(head) + "\n" + json.dumps(values(names, collector, pipeline), indent=2) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("projects", help="output of `kubectl get projects.management.cattle.io -A -o json`")
    ap.add_argument("--out", required=True, help="values file to write")
    ap.add_argument("--collector", default="daemon",
                    help="name of the collector under `collectors:` that has the metrics pipeline (default daemon)")
    ap.add_argument("--pipeline", metavar="LIST",
                    help="comma-separated processors of the metrics pipeline, in order and complete, e.g. "
                         f"k8s_attributes,{PROCESSOR},batch; must contain {PROCESSOR} after k8s_attributes")
    args = ap.parse_args()
    names = bd.load_rancher_projects(args.projects)
    if not names:
        sys.exit(f"no Projects in {args.projects}; is it from the Rancher local cluster?")
    pipeline = [p.strip() for p in args.pipeline.split(",") if p.strip()] if args.pipeline else None
    if pipeline is not None and PROCESSOR not in pipeline:
        ap.error(f"--pipeline must contain {PROCESSOR}")
    with open(args.out, "w") as f:
        f.write(render(names, args.collector, pipeline))
    print(f"wrote {args.out}: {len(names)} Projects")


if __name__ == "__main__":
    main()
